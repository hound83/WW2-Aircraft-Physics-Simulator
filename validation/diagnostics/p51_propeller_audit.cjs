'use strict';
const fs=require('node:fs'),path=require('node:path');
const M=require('../../src/physics.js'),D=require('../../aircraft/cases.json');
const L=require('../../references/p51-propeller-efficiency-audit.json'),T=require('../lib/propeller_transfer.cjs');
const S=require('./p51_climb_states.cjs'),G=require('../baseline/p51_power_required_source_v16.json');
const ac=D.aircraft.p51b,profiles=['C','D','N','M'],root=path.resolve(__dirname,'../..');
function polar(profile){
 const p=M.cd0FromAnchor(ac,profile,.78);
 if(!p?.valid)throw Error('Invalid candidate anchor polar: '+profile);
 return {cd0:p.cd0,e:.78,source:'Original sea-level speed anchor; candidate '+profile+'; no climb/Figure 5 fit'};
}
function describe(profile,altFt,tasMph,bhp,rating,engineRpm=3000){
 const p=M.propEta(ac,altFt,tasMph,bhp,profile,rating,{engineRpmOverride:engineRpm});
 const dims=M.propEta(ac,altFt,tasMph,bhp,'C',rating,{engineRpmOverride:engineRpm});
 return {eta:p?.eta??null,J:dims?.J??null,Cp:dims?.Cp??null,tipMach:dims?.tipMach??null,
  engineRpm,chartWithinCp:p?.chartWithinCp??null,
  transfer:T.assess(L.profiles[profile],L.target,dims)};
}
function run(){
 const points=S.readPoints(),weight=points.find(p=>p.kind==='weight'&&p.altFt===2200).bounds;
 const original=polar('C'),anchor=ac.calibration,anchorShaft=M.shaftPower(ac,anchor.altFt,anchor.rating,anchor.gear).bhp;
 const variants=[];
 for(const profile of profiles){
  const fitted=polar(profile),anchorProp=describe(profile,anchor.altFt,anchor.tasMph,anchorShaft,anchor.rating);
  const speeds={
   fixedOriginalPolarMph:M.maxSpeed(ac,anchor.altFt,{profile,polar:original,rating:anchor.rating,gear:anchor.gear}),
   candidateAnchoredPolarMph:M.maxSpeed(ac,anchor.altFt,{profile,polar:fitted,rating:anchor.rating,gear:anchor.gear})
  };
  const figure5=G.points.map(p=>{
   const prop=describe(profile,G.altitudeFt,p.tasMph,p.testBhp,'67inHg',p.engineRpm);
   const drag=M.dragBreakdown(ac,G.altitudeFt,p.tasMph,G.nominalWeightLb,fitted.cd0,.78);
   const predictedRequiredBhp=prop.eta>0?drag.requiredHp/prop.eta:null;
   return {...p,prop,predictedRequiredBhp,residualBhp:predictedRequiredBhp===null?null:predictedRequiredBhp-p.testBhp,
    role:'already-exposed related-programme diagnostic; inherited approximate reading; not fitted'};
  });
  const climb=[];
  for(const rating of ['67inHg','75inHg']){
   const power=points.find(p=>p.kind==='power'&&p.altFt===2200&&p.rating===rating).bounds;
   const reportedFpm=rating==='67inHg'?3820:4380;
   for(const [polarPolicy,pol]of [['original-C',original],['candidate-anchor',fitted]]){
    const rows=[];
    for(const bhp of [power[0],(power[0]+power[1])/2,power[1]])for(const weightLb of [weight[0],9335,weight[1]]){
     const r=S.chartPrediction(2200,rating,bhp,weightLb,profile,pol);
     const prop=describe(profile,2200,r.tasMph,bhp,rating);
     rows.push({bhp,weightLb,tasMph:r.tasMph,climbFpm:r.climbFpm,prop});
    }
    const min=rows.reduce((a,b)=>a.climbFpm<b.climbFpm?a:b),max=rows.reduce((a,b)=>a.climbFpm>b.climbFpm?a:b);
    climb.push({rating,reportedFpm,polarPolicy,min,max,samples:rows.length,rows,
     interpretation:'Three power / three weight samples; optimized 100-290 mph TAS at 1 mph. Weight curve is a counterfactual, not matched climb mass. Finite-grid range is not a bound.'});
   }
  }
  variants.push({profile,source:L.profiles[profile],cd0:fitted.cd0,anchorProp,speeds,figure5,
   diagnosticFigure5MaeBhp:figure5.reduce((s,p)=>s+Math.abs(p.residualBhp),0)/figure5.length,climb,
   adoptedAsDefault:profile==='C',acceptedAsMeasuredInstalledModel:false});
 }
 return {schema:1,version:require('../../package.json').version,scope:'Mustang source-transfer and coupled candidate audit',sourceRegister:'references/p51-propeller-efficiency-audit.json',
  calibration:'Existing sea-level speed anchor only; original versus candidate polar explicitly separated',
  checkpointPolicy:L.constraints.checkpoints,variants,acceptedDefaultChange:null,
  conclusion:'Inspected evidence does not establish a matched installed target map. D/N/M remain research transfers or assumptions; lower climb residual alone cannot validate them. Preserve C and unresolved historical accuracy.'};
}
function writeReport(){
 const r=run(),f=x=>Number.isFinite(x)?x.toFixed(2):'unresolved';
 fs.writeFileSync(path.join(root,'validation/current/p51-propeller-audit.json'),JSON.stringify(r,null,2)+'\n');
 const lines=['# Mustang propeller efficiency: source and candidate audit','',
 'Generated by npm run check. No climb or Figure 5 point is fitted and no default physical correction is adopted.','',
 '## What the source review establishes','',
 'The [source register](../references/p51-propeller-efficiency-audit.json) distinguishes verified identity, generic theory, OCR and transferred experiments. [TK589 section 2.5](https://www.wwiiaircraftperformance.com/org/p-51/tk589.html) corroborates the same K.6523A-24 blade drawing on a different Mustang, but supplies no installed-efficiency surface. The target remains 43-24777.','',
 '[NACA L4L18](https://ntrs.nasa.gov/citations/19780078569) concerns another P-51B/engine. Official OCR gives a 6487-24 designation with an ambiguous prefix and identifies power-estimate/torque-measurement limitations; original pixels were not newly verified. It cannot be promoted to a measured target map.','',
 'Inherited [1941 report text](https://ntrs.nasa.gov/citations/19930093644) concerns other test blades/solidities; [1944 charts](https://ntrs.nasa.gov/citations/19930093312) supply a general method. Neither establishes target loss coefficients. Existing N/M chart readings and P-47D transfers were reused, not freshly digitized. No applicable installed map was obtained in these inspected sources.','',
 '## Source transfer and operating domain','',
 '| Profile | Basis | Measured target installation? |','|---|---|---|'];
 for(const v of r.variants)lines.push('| '+v.profile+' | '+v.source.sourceKind+' | no |');
 lines.push('','Each recorded state carries J, Cp, helical tip Mach, actual source RPM and explicit transfer blockers. N/M Cp clamping cannot pass as in-domain evidence. Missing Mach coverage stays missing; no invented verified Mach threshold is introduced. D retains its assumed 0.85 loss fraction. C remains a heuristic default, not validated measured eta.','',
 '## Speed anchor and level-flight checkpoints','',
 '| Profile | CD0 from original speed anchor | Anchor mph with original C polar | Anchor mph after candidate reanchor | Figure 5 diagnostic MAE BHP |','|---|---:|---:|---:|---:|');
 for(const v of r.variants)lines.push('| '+v.profile+' | '+v.cd0.toFixed(5)+' | '+f(v.speeds.fixedOriginalPolarMph)+' | '+f(v.speeds.candidateAnchoredPolarMph)+' | '+f(v.diagnosticFigure5MaeBhp)+' |');
 lines.push('','Candidate reanchoring uses only the same original sea-level speed observation; it changes the inferred polar and is not independent validation. Figure 5 keeps the recorded 2100/2300/2700/3000 RPM and approximate inherited readings. All six signed residuals are retained in JSON. MAE here summarizes excluded diagnostics, not matched-condition accuracy. These already-exposed data are not new independent holdouts.','',
 '## Joint chart-state climb experiments','',
 '| Profile | Rating | Polar | Sampled climb range ft/min | Reported ft/min |','|---|---|---|---:|---:|');
 for(const v of r.variants)for(const c of v.climb)lines.push('| '+v.profile+' | '+c.rating+' | '+c.polarPolicy+' | '+f(c.min.climbFpm)+'-'+f(c.max.climbFpm)+' | '+c.reportedFpm+' |');
 lines.push('','Each row samples low/middle/high chart BHP and low/9335/high normalization weight, optimizing TAS at 1 mph from 100 to 290 mph. This reuses the shared solver and recomputes efficiency with power/speed. The weight interval remains explicitly counterfactual. Nine samples do not establish a continuous envelope or historical error bound. Source airspeed/mass and engine-chart accuracy are still unresolved. A closer climb result cannot override blade/domain/installation blockers or justify a coefficient fit.','',
 '## Decision and release','',
 r.conclusion,'',
 'Version 2.6.0 packages the accumulated source gates, diagnostics and reconstruction as a research increment. Default coefficients and numerical aircraft inputs remain unchanged. Historical stall calibration, independent accuracy and 5:1 resolution remain unresolved. The runnable build carries the new research-version label while preserving the frozen original template. See [release notes](../releases/v2.6.0.md) and [current validation](CURRENT_VALIDATION.md).','');
 fs.writeFileSync(path.join(root,'docs/P51_PROPELLER_EFFICIENCY_AUDIT.md'),lines.join('\n'));
 return r;
}
if(require.main===module){writeReport();console.log('Propeller audit: C/D/N/M, source-domain blockers and coupled anchor/climb/Figure 5 diagnostics.');}
module.exports={polar,describe,run,writeReport};
