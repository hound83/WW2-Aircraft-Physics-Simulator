import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {shaftHorsepower,evaluatePoint,bestRateClimb,maxLevelSpeed} from './performance_engine.mjs';
const a=JSON.parse(readFileSync(new URL('./p51b15.json',import.meta.url),'utf8'));
assert(a.source.report.includes('Eng-47-1749-A'));
const low10=shaftHorsepower(a,{altFt:10300,rating:'67inHg',gear:'low'});
const low17=shaftHorsepower(a,{altFt:17000,rating:'67inHg',gear:'low'});
const high24=shaftHorsepower(a,{altFt:24000,rating:'67inHg',gear:'high'});
const high28=shaftHorsepower(a,{altFt:28000,rating:'67inHg',gear:'high'});
const high26=shaftHorsepower(a,{altFt:26000,rating:'67inHg',gear:'high'});
assert.equal(low10.manifoldInHg,67);
assert.equal(low17.manifoldInHg,52.8);
assert.equal(high24.manifoldInHg,67);
assert.equal(high28.manifoldInHg,57.3);
assert.equal(high26.manifoldInHg,62.15);
assert.equal(high28.requestedManifoldInHg,67);
assert.equal(high28.boostLimited,true);
assert.equal(high24.boostLimited,false);
assert.equal(shaftHorsepower(a,{altFt:20800,rating:'75inHg',gear:'high'}).criticalAltitudeFt,20800);
assert.throws(()=>shaftHorsepower(a,{altFt:22000,rating:'75inHg',gear:'high'}),/No extrapolation/);
const stalled=evaluatePoint(a,{altFt:20800,speedMphTas:130,gear:'high'});
assert.equal(stalled.flightValidity.feasibleUnderProvisionalCLmax,false);
assert.equal(stalled.power.rateClimbFtMin,null);
assert.equal(stalled.power.levelAccelerationMps2,null);
assert.equal(stalled.maneuver.instantaneousG,null);
assert.equal(stalled.maneuver.sustainedG,null);
assert.equal(stalled.maneuver.instantaneousTurn.degPerSec,null);
assert.equal(stalled.maneuver.sustainedTurn.degPerSec,null);
assert(stalled.power.rawUnconstrainedRateClimbFtMin>0,'the prior misleading positive number remains available ONLY as an invalid raw mathematical balance');
const flying=evaluatePoint(a,{altFt:20800,speedMphTas:300,gear:'high'});
assert.equal(flying.flightValidity.feasibleUnderProvisionalCLmax,true);
assert(Number.isFinite(flying.power.rateClimbFtMin));
assert(Number.isFinite(maxLevelSpeed(a,{altFt:24000,gear:'high'})));
assert(Number.isFinite(bestRateClimb(a,{altFt:2200,gear:'low'}).rateClimbFtMin));
console.log('PASS v0.3: MAP requested vs available, rating critical heights, strict no extrapolation, stall validation and source ID');
console.log('130 mph / 20,800 ft: invalid predicted stall; raw unconstrained ROC=',stalled.power.rawUnconstrainedRateClimbFtMin.toFixed(1),'ft/min, achieved ROC=null');
console.log('67 inHg requested, 28,000 ft high: achieved pressure=',high28.manifoldInHg,'inHg');
