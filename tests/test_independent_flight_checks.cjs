'use strict';
const assert=require('node:assert/strict');
const M=require('../src/physics.js'),D=require('../aircraft/cases.json').aircraft;
const E=require('../calibration/flight-envelope.json');
const S=require('../references/independent-flight-checks.json');
const report=require('../validation/diagnostics/independent_flight_checks.cjs').run();
const close=(a,b,tol=1e-6)=>assert.ok(Number.isFinite(a)&&Math.abs(a-b)<tol,`${a} versus ${b}`);
const ac=D.bf109f4,model=E.aircraft.bf109f4.inletTransfer;
const opts={profile:'P',flightEnvelope:E,engineModel:'inlet-transfer',rating:'combat',gear:'fluid'};
const point=(alt,tas,extra={})=>M.evaluated(ac,alt,tas,{...opts,...extra});
assert.equal(model.engineRpm,S.db601e.rpm);
assert.equal(model.referenceTasMph,S.db601e.fullThrottleMph);
close(model.referenceAltFt*.3048,6000);
const critical=point(model.referenceAltFt,model.referenceTasMph);
close(critical.engine.estimatedManifoldAta,1.3);
close(critical.engine.bhp,M.shaftPower(ac,0,'combat','fluid').bhp);
close(M.maxSpeed(ac,0,opts),ac.calibration.tasMph);
assert.ok(point(21000,400).engine.bhp>point(21000,200).engine.bhp);
assert.ok(point(21000,200).engine.bhp>point(23000,200).engine.bhp);
for(const extra of [{rating:'emergency'},{gear:'low'},{profile:'C'},{chargeExponent:.5},{ramRecovery:1.1}]){
 assert.equal(point(22000,300,extra).status,'no-engine-source');
}
assert.equal(point(23001,300).status,'no-engine-source');
assert.equal(M.evaluated({...ac,stallIdentity:{...ac.stallIdentity,specimen:'14026'}},22000,300,opts).status,'no-engine-source');
assert.equal(report.f4.defaultAtCheck,null);
assert.equal(report.f4.emergencyAtCheck,null);
close(report.f4.predicted*1.609344,633.2152313432);
assert.ok(report.f4.sensitivity.every(r=>Math.abs(r.predicted-report.f4.observed)<Math.abs(report.f4.legacy-report.f4.observed)));
assert.ok(report.f4.alternateScanTextPrediction>report.f4.predicted);
assert.equal(report.calibrationTargetCount,0);
assert.equal(report.exactSpecimenIndependentCases,0);

assert.equal(report.spitfire.scored,16);
assert.equal(report.spitfire.rows.at(-1).working,null);
assert.ok(report.spitfire.workingMae>report.spitfire.baseMae+2);
assert.ok(report.spitfire.boostOnlyMae>report.spitfire.baseMae+2);
assert.ok(Math.abs(report.mustang.working-report.mustang.observed)>Math.abs(report.mustang.base-report.mustang.observed));
assert.ok(report.thunderbolt.reportedPowerMae<report.thunderbolt.chartMae);
const production=report.thunderboltProduction;
assert.equal(production.level.length,3);
assert.equal(production.climb.length,5);
assert.ok(production.levelMae<2.4);
assert.ok(production.openClimbMae<production.fixedCd0ClimbMae);
assert.ok(production.fixedCd0ClimbMae<production.cleanClimbMae);
const last=production.climb.at(-1);
assert.ok(Math.abs(last.open-last.observed)>Math.abs(last.fixedCd0-last.observed));
console.log('PASS archival power reference, rating/domain and source identity gates, external same-type P-47B and nonportable transfer checks');
